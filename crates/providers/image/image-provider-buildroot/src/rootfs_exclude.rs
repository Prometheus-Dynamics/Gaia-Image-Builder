//! Leaving Buildroot packages out of the root filesystem (`[image.rootfs]
//! exclude_packages`).
//!
//! One Buildroot tree builds every package; an image can still leave some of
//! them out of `target/`, so its filesystem images do not ship them. Nothing
//! is rebuilt. The files are removed by a post-build script that Gaia adds to
//! the image's make, which Buildroot runs in `target-finalize` before the
//! user's post-build scripts and before any filesystem image is made.
//!
//! Buildroot copies each package's files from its per-package directory into
//! `target/` on every finalize, so an image without the exclusion gets the
//! files back. That depends on `BR2_PER_PACKAGE_DIRECTORIES` (the parallel
//! package policy), which is why an exclusion needs it.
//!
//! What is removed: the paths `build/packages-file-list.txt` lists for an
//! excluded package. A path a kept package also lists stays. Directories are
//! not listed there, so an excluded package's directory goes when the removal
//! leaves it empty.
//!
//! With `drop_shadowed_modules`, the script then removes each in-tree module
//! (`<modules>/<release>/kernel/...`) that a module of the same name under
//! `updates/` shadows: modprobe loads the `updates/` one (depmod's search
//! order), so the in-tree copy is never loaded. It runs after the exclusion,
//! so an image that leaves out the package with the `updates/` module keeps
//! the in-tree one.
//!
//! Checks: before the make, every name is a target package of the graph and
//! no kept target package depends on one (see [`check_rootfs_exclude_graph`]).
//! After the make and before the images, no object left in `target/` needs a
//! name that only a removed file provided (see `verify`).
use super::*;
use crate::rootfs_exclude_elf::{ElfNames, elf_names, has_elf_magic};
use sha2::{Digest, Sha256};
use std::collections::VecDeque;

/// The directory, next to the output tree, with the staged script, the
/// removal list it writes and the marker it leaves when it ran.
pub(crate) const ROOTFS_EXCLUDE_DIR: &str = ".gaia-rootfs-exclude";
const SCRIPT_FILE: &str = "exclude.sh";
const REMOVALS_FILE: &str = "removals.tsv";
const APPLIED_MARKER: &str = "applied";
/// The digest of the exclusion the last finalize of `target/` applied: empty
/// when it applied none. A finalize records it; a make skips the finalize only
/// when it matches what the make would apply.
pub(crate) const APPLIED_STATE: &str = ".gaia-rootfs-exclude-applied";

/// The post-build script. `@LIST@`, `@REMOVALS@`, `@MARKER@`, `@EXCLUDED@`,
/// `@SHADOWED@`, `@NODBUS@`, `@NODBUS_BLOCK@` and `@NONCE@` are replaced; the script takes the target
/// directory as `$1`.
const SCRIPT_TEMPLATE: &str = r#"#!/bin/sh
# Generated by Gaia (image.rootfs.exclude_packages): leaves the files of the
# excluded packages out of target/, before the other post-build scripts and
# the filesystem images.
set -eu
target=$1
list=@LIST@
removals=@REMOVALS@
marker=@MARKER@
excluded=@EXCLUDED@
drop_shadowed=@SHADOWED@
drop_dbus=@NODBUS@
tab=$(printf '\t')
if [ ! -f "$list" ]; then
    echo "Gaia: $list is missing: cannot leave packages out of the rootfs" >&2
    exit 1
fi
# The removal list: each path an excluded package lists, as "remove", or as
# "shared" when a kept package lists it too (then it stays).
awk -v excluded="$excluded" '
  BEGIN { n = split(excluded, names, " "); for (i = 1; i <= n; i++) excl[names[i]] = 1 }
  {
    pos = index($0, ","); if (pos == 0) next
    pkg = substr($0, 1, pos - 1); path = substr($0, pos + 1); sub(/^\.\//, "", path)
  }
  NR == FNR { if (!(pkg in excl)) kept[path] = 1; next }
  (pkg in excl) { print ((path in kept) ? "shared" : "remove") "\t" pkg "\t" path }
' "$list" "$list" > "$removals"
# Removes the rows of $1 whose action is $2.
remove_rows() {
    while IFS=$tab read -r action pkg rel; do
        [ "$action" = "$2" ] || continue
        file=$target/$rel
        if [ -L "$file" ] || [ -f "$file" ]; then
            rm -f -- "$file"
        fi
        # Directories this removal may have emptied; rmdir keeps any non-empty one.
        dir=$(dirname -- "$file")
        while [ "${dir#"$target"/}" != "$dir" ]; do
            rmdir -- "$dir" 2>/dev/null || break
            dir=$(dirname -- "$dir")
        done
    done < "$1"
}
remove_rows "$removals" remove
@NODBUS_BLOCK@# In-tree modules an updates/ module of the same name shadows (modprobe
# names: "-" and "_" are the same), as "shadowed" rows, after the exclusion.
if [ "$drop_shadowed" = 1 ]; then
    shadowed=$removals.shadowed
    : > "$shadowed"
    for modules in usr/lib/modules lib/modules; do
        # Merged /usr: lib/modules is usr/lib/modules.
        [ -L "$target/${modules%%/*}" ] && continue
        for release in "$target/$modules"/*; do
            [ -d "$release/updates" ] && [ -d "$release/kernel" ] || continue
            find "$release/updates" "$release/kernel" -type f \( -name '*.ko' -o -name '*.ko.xz' \
                -o -name '*.ko.zst' -o -name '*.ko.gz' \) | LC_ALL=C sort | awk -v prefix="$target/" -v list="$list" '
              BEGIN {
                while ((getline line < list) > 0) {
                  pos = index(line, ","); if (pos == 0) continue
                  path = substr(line, pos + 1); sub(/^\.\//, "", path); owner[path] = substr(line, 1, pos - 1)
                }
              }
              {
                rel = substr($0, length(prefix) + 1); n = split(rel, parts, "/"); name = parts[n]
                sub(/\.ko(\.(xz|zst|gz))?$/, "", name); gsub(/-/, "_", name)
                if (rel ~ /\/updates\//) updates[name] = 1
                else { count++; kernel_rel[count] = rel; kernel_name[count] = name }
              }
              END {
                for (i = 1; i <= count; i++) if (kernel_name[i] in updates) {
                  rel = kernel_rel[i]; print "shadowed\t" ((rel in owner) ? owner[rel] : "linux") "\t" rel
                }
              }' >> "$shadowed"
        done
    done
    remove_rows "$shadowed" shadowed
    cat "$shadowed" >> "$removals"
    rm -f -- "$shadowed"
fi
# Buildroot ran depmod in target-finalize, before this script: a removed
# kernel module would stay in modules.dep. Index again every kernel version
# that lost a module.
kvers=$(awk -F "$tab" '($1 == "remove" || $1 == "shadowed") && $3 ~ /^(usr\/)?lib\/modules\/[^\/]+\/.*\.ko/ {
    n = split($3, parts, "/"); for (i = 1; i < n; i++) if (parts[i] == "modules") { print parts[i + 1]; break }
}' "$removals" | sort -u)
if [ -n "$kvers" ]; then
    depmod_bin=${HOST_DIR:-}/sbin/depmod
    [ -x "$depmod_bin" ] || depmod_bin=depmod
    for kver in $kvers; do
        if [ -d "$target/lib/modules/$kver" ] || [ -d "$target/usr/lib/modules/$kver" ]; then
            "$depmod_bin" -a -b "$target" "$kver" || {
                echo "Gaia: depmod failed for kernel $kver after leaving modules out of the rootfs" >&2
                exit 1
            }
        fi
    done
fi
printf '%s\n' @NONCE@ > "$marker"
"#;

/// The image's excluded package names, sorted and without duplicates.
pub(crate) fn rootfs_exclude_names(image: &ImageSpec) -> Vec<String> {
    let ImageDefinition::Buildroot(buildroot) = &image.definition else {
        return Vec::new();
    };
    let mut names = buildroot.rootfs_exclude_packages.clone();
    names.sort();
    names.dedup();
    names
}

/// Whether the image drops in-tree modules that `updates/` ones shadow.
pub(crate) fn rootfs_drop_shadowed_modules(image: &ImageSpec) -> bool {
    matches!(&image.definition, ImageDefinition::Buildroot(buildroot) if buildroot.rootfs_drop_shadowed_modules)
}

/// What the script drops besides the excluded packages.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub(crate) struct RootfsDrops {
    /// In-tree modules that `updates/` ones shadow (`drop_shadowed_modules`).
    pub(crate) shadowed_modules: bool,
    /// The D-Bus daemon (`drop_dbus_daemon`).
    pub(crate) dbus_daemon: bool,
}

impl RootfsDrops {
    pub(crate) fn of(image: &ImageSpec) -> Self {
        Self {
            shadowed_modules: rootfs_drop_shadowed_modules(image),
            dbus_daemon: rootfs_drop_dbus_daemon(image),
        }
    }

    pub(crate) fn any(self) -> bool {
        self.shadowed_modules || self.dbus_daemon
    }
}

/// The digest of what the script applies: the exclusion list's, extended for
/// each drop that is on. Empty for none.
pub(crate) fn staged_digest(names: &[String], drops: RootfsDrops) -> String {
    let mut digest = rootfs_exclude_digest(names);
    for (on, tag) in [
        (
            drops.shadowed_modules,
            &b"gaia-rootfs-drop-shadowed-modules\0"[..],
        ),
        (drops.dbus_daemon, &b"gaia-rootfs-drop-dbus-daemon\0"[..]),
    ] {
        if on {
            let mut hasher = Sha256::new();
            hasher.update(tag);
            hasher.update(digest.as_bytes());
            digest = hex(&hasher.finalize());
        }
    }
    digest
}

/// The digest of an exclusion list: empty for none.
pub(crate) fn rootfs_exclude_digest(names: &[String]) -> String {
    if names.is_empty() {
        return String::new();
    }
    let mut hasher = Sha256::new();
    hasher.update(b"gaia-rootfs-exclude\0");
    for name in names {
        hasher.update(name.as_bytes());
        hasher.update(b"\0");
    }
    hex(&hasher.finalize())
}

/// The exclusion `target/` was last finalized with ("" for none).
pub(crate) fn applied_rootfs_exclude(output_dir: &Path) -> String {
    fs::read_to_string(output_dir.join(APPLIED_STATE))
        .map(|digest| digest.trim().to_string())
        .unwrap_or_default()
}

/// Records the exclusion the finalize that just succeeded applied.
pub(crate) fn record_applied_rootfs_exclude(
    output_dir: &Path,
    digest: &str,
) -> Result<(), ImageProviderError> {
    let path = output_dir.join(APPLIED_STATE);
    fs::write(&path, format!("{digest}\n"))
        .map_err(|error| io_failure("failed to record the rootfs exclusion", &path, error))
}

/// A Buildroot package every target package may depend on without needing its
/// files: left out of the dependency check.
fn is_ignored_dependency(name: &str) -> bool {
    name == "skeleton" || name.starts_with("toolchain") || name.starts_with("host-")
}

/// The graph checks, before anything is removed: each name is a target
/// package of `graph`, and no kept target package depends on one of them.
pub(crate) fn check_rootfs_exclude_graph(
    graph: &PackageGraph,
    names: &[String],
) -> Result<(), ImageProviderError> {
    for name in names {
        match graph.packages.get(name) {
            Some(package) if package.kind == "target" => {}
            Some(package) => {
                return Err(exclude_error(format!(
                    "'{name}' is a {} package; only target packages can be left out of the rootfs",
                    package.kind
                )));
            }
            None => {
                return Err(exclude_error(format!(
                    "'{name}' is not a package of this Buildroot tree"
                )));
            }
        }
    }
    let excluded: BTreeSet<&str> = names.iter().map(String::as_str).collect();
    for (kept, package) in &graph.packages {
        if package.kind != "target" || excluded.contains(kept.as_str()) {
            continue;
        }
        if let Some(path) = dependency_path_to(graph, kept, &excluded) {
            let excluded_name = path.last().cloned().unwrap_or_default();
            return Err(exclude_error(format!(
                "kept package '{kept}' depends on excluded package '{excluded_name}' ({})",
                path.join(" -> ")
            )));
        }
    }
    Ok(())
}

/// The target-package dependency path from `start` to an excluded package.
fn dependency_path_to(
    graph: &PackageGraph,
    start: &str,
    excluded: &BTreeSet<&str>,
) -> Option<Vec<String>> {
    let mut parent: BTreeMap<&str, &str> = BTreeMap::new();
    let mut seen: BTreeSet<&str> = BTreeSet::from([start]);
    let mut queue = VecDeque::from([start]);
    while let Some(current) = queue.pop_front() {
        let Some(package) = graph.packages.get(current) else {
            continue;
        };
        for dependency in &package.dependencies {
            let dependency = dependency.as_str();
            let is_target = graph
                .packages
                .get(dependency)
                .is_some_and(|found| found.kind == "target");
            if !is_target || is_ignored_dependency(dependency) || !seen.insert(dependency) {
                continue;
            }
            parent.insert(dependency, current);
            if excluded.contains(dependency) {
                let mut path = vec![dependency.to_string()];
                let mut node = dependency;
                while let Some(&up) = parent.get(node) {
                    path.push(up.to_string());
                    node = up;
                }
                path.reverse();
                return Some(path);
            }
            queue.push_back(dependency);
        }
    }
    None
}

/// The exclusion as staged for one make.
#[derive(Debug)]
pub(crate) struct StagedRootfsExclude {
    /// The post-build script, run first among the post-build scripts.
    pub(crate) script: PathBuf,
    pub(crate) names: Vec<String>,
    pub(crate) drops: RootfsDrops,
    pub(crate) digest: String,
    output_dir: PathBuf,
    marker: PathBuf,
    nonce: String,
}

/// Stages the exclusion of `names` (and of what `drops` turns on) for the make
/// of `output_dir`. Returns `None` when there is nothing to leave out.
pub(crate) fn stage_rootfs_exclude(
    output_dir: &Path,
    names: &[String],
    drops: RootfsDrops,
) -> Result<Option<StagedRootfsExclude>, ImageProviderError> {
    let dir = output_dir.join(ROOTFS_EXCLUDE_DIR);
    remove_path_if_exists(&dir)?;
    if names.is_empty() && !drops.any() {
        return Ok(None);
    }
    fs::create_dir_all(&dir)
        .map_err(|error| io_failure("failed to create the rootfs exclusion dir", &dir, error))?;
    let digest = staged_digest(names, drops);
    let nonce = {
        let mut hasher = Sha256::new();
        hasher.update(digest.as_bytes());
        hasher.update(
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .map(|duration| duration.as_nanos())
                .unwrap_or_default()
                .to_le_bytes(),
        );
        hasher.update(std::process::id().to_le_bytes());
        hex(&hasher.finalize())
    };
    let script = dir.join(SCRIPT_FILE);
    let removals = dir.join(REMOVALS_FILE);
    let marker = dir.join(APPLIED_MARKER);
    let body = SCRIPT_TEMPLATE
        .replace(
            "@LIST@",
            &shell_quote(
                &output_dir
                    .join("build/packages-file-list.txt")
                    .display()
                    .to_string(),
            ),
        )
        .replace("@REMOVALS@", &shell_quote(&removals.display().to_string()))
        .replace("@MARKER@", &shell_quote(&marker.display().to_string()))
        .replace("@EXCLUDED@", &shell_quote(&names.join(" ")))
        .replace("@SHADOWED@", if drops.shadowed_modules { "1" } else { "0" })
        .replace("@NODBUS@", if drops.dbus_daemon { "1" } else { "0" })
        .replace("@NODBUS_BLOCK@", NO_DBUS_BLOCK)
        .replace("@NONCE@", &shell_quote(&nonce));
    fs::write(&script, body).map_err(|error| {
        io_failure(
            "failed to write the rootfs exclusion script",
            &script,
            error,
        )
    })?;
    #[cfg(unix)]
    fs::set_permissions(&script, fs::Permissions::from_mode(0o755)).map_err(|error| {
        io_failure(
            "failed to mark the rootfs exclusion script executable",
            &script,
            error,
        )
    })?;
    Ok(Some(StagedRootfsExclude {
        script,
        names: names.to_vec(),
        drops,
        digest,
        output_dir: output_dir.to_path_buf(),
        marker,
        nonce,
    }))
}

/// What the exclusion removed, for the run's messages.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct RootfsExcludeSummary {
    pub(crate) names: Vec<String>,
    pub(crate) files: usize,
    pub(crate) bytes: u64,
    /// Removal candidates a kept package also lists: kept in `target/`.
    pub(crate) shared: Vec<String>,
    /// In-tree modules removed because an `updates/` module shadows them.
    pub(crate) shadowed: Vec<String>,
    pub(crate) shadowed_bytes: u64,
    /// The D-Bus daemon's files removed (`drop_dbus_daemon`), when on.
    pub(crate) no_dbus: Option<(usize, u64)>,
}

impl RootfsExcludeSummary {
    /// `rootfs: left out N packages (a, b): M files, X MiB`.
    pub(crate) fn message(&self) -> String {
        let count = self.names.len();
        let noun = if count == 1 { "package" } else { "packages" };
        format!(
            "rootfs: left out {count} {noun} ({}): {} files, {:.1} MiB",
            self.names.join(", "),
            self.files,
            self.bytes as f64 / (1024.0 * 1024.0)
        )
    }

    /// `rootfs: dropped N in-tree modules that updates/ modules shadow (a, b): X KiB`,
    /// when any were.
    pub(crate) fn shadowed_message(&self) -> Option<String> {
        if self.shadowed.is_empty() {
            return None;
        }
        let names = self
            .shadowed
            .iter()
            .filter_map(|rel| rel.rsplit('/').next())
            .collect::<Vec<_>>();
        Some(format!(
            "rootfs: dropped {} in-tree module(s) that updates/ modules shadow ({}): {:.1} KiB",
            self.shadowed.len(),
            names.join(", "),
            self.shadowed_bytes as f64 / 1024.0
        ))
    }

    /// `rootfs: dropped the D-Bus daemon ...`, when it was.
    pub(crate) fn no_dbus_message(&self) -> Option<String> {
        self.no_dbus
            .map(|(files, bytes)| no_dbus_message(files, bytes))
    }

    /// The shared paths kept, when there are any.
    pub(crate) fn shared_message(&self) -> Option<String> {
        if self.shared.is_empty() {
            return None;
        }
        let shown = self.shared.iter().take(10).cloned().collect::<Vec<_>>();
        Some(format!(
            "rootfs: kept {} path(s) that a kept package also lists: {}",
            self.shared.len(),
            shown.join(", ")
        ))
    }
}

impl StagedRootfsExclude {
    /// Make variables for the run: each removed package's `<PKG>_PERMISSIONS`
    /// set empty. Buildroot's makedevs applies them after the post-build
    /// scripts and fails on a file the removal took (dbus's
    /// `dbus-daemon-launch-helper`, for one).
    pub(crate) fn make_overrides(&self) -> Vec<String> {
        let mut packages: Vec<&str> = self.names.iter().map(String::as_str).collect();
        if self.drops.dbus_daemon && !packages.contains(&"dbus") {
            packages.push("dbus");
        }
        packages
            .into_iter()
            .map(|name| {
                format!(
                    "{}_PERMISSIONS=",
                    name.to_ascii_uppercase().replace('-', "_")
                )
            })
            .collect()
    }

    /// Whether Buildroot ran the script during the last make.
    pub(crate) fn applied(&self) -> bool {
        fs::read_to_string(&self.marker).is_ok_and(|marker| marker.trim() == self.nonce)
    }

    /// Checks the removal the make ran and returns what it removed. Errors when
    /// the script did not run, a removed path is still there, or an object left
    /// in `target/` needs a name that only a removed file provided.
    pub(crate) fn verify(&self) -> Result<RootfsExcludeSummary, ImageProviderError> {
        if !self.applied() {
            return Err(ImageProviderError::backend_command(
                "Buildroot did not run the rootfs exclusion post-build script; the excluded packages may be in the rootfs",
            ));
        }
        let removals_path = self.output_dir.join(ROOTFS_EXCLUDE_DIR).join(REMOVALS_FILE);
        let removals = fs::read_to_string(&removals_path).map_err(|error| {
            io_failure(
                "failed to read the rootfs removal list",
                &removals_path,
                error,
            )
        })?;
        let mut removed = Vec::new();
        let mut shared = Vec::new();
        let mut shadowed = Vec::new();
        let mut no_dbus = Vec::new();
        for line in removals.lines() {
            let mut fields = line.splitn(3, '\t');
            match (fields.next(), fields.next(), fields.next()) {
                (Some("remove"), Some(pkg), Some(rel)) => {
                    removed.push((pkg.to_string(), rel.to_string()))
                }
                (Some("shared"), Some(_), Some(rel)) => shared.push(rel.to_string()),
                (Some("shadowed"), Some(pkg), Some(rel)) => {
                    shadowed.push((pkg.to_string(), rel.to_string()))
                }
                (Some("nodbus"), Some(pkg), Some(rel)) => {
                    no_dbus.push((pkg.to_string(), rel.to_string()))
                }
                _ => {}
            }
        }

        let target = self.output_dir.join("target");
        let mut shadowed_bytes = 0u64;
        for (pkg, rel) in &shadowed {
            if fs::symlink_metadata(target.join(rel)).is_ok() {
                return Err(exclude_error(format!(
                    "the shadowed module '{rel}' is still in target/ after the removal"
                )));
            }
            shadowed_bytes += fs::metadata(
                self.output_dir
                    .join("per-package")
                    .join(pkg)
                    .join("target")
                    .join(rel),
            )
            .map(|metadata| metadata.len())
            .unwrap_or_default();
        }
        for (_, rel) in &removed {
            if fs::symlink_metadata(target.join(rel)).is_ok() {
                return Err(exclude_error(format!(
                    "'{rel}' is in target/ again after the removal: a later rootfs overlay or post-build script put it back"
                )));
            }
        }
        let no_dbus = if self.drops.dbus_daemon {
            Some(self.verify_no_dbus(&target, &no_dbus)?)
        } else {
            None
        };

        // Names only the removed files provide: their basenames and sonames,
        // read from the per-package trees, which the removal leaves alone.
        let mut removed_providers: BTreeMap<String, String> = BTreeMap::new();
        let mut bytes = 0u64;
        for (pkg, rel) in &removed {
            let per_package = self
                .output_dir
                .join("per-package")
                .join(pkg)
                .join("target")
                .join(rel);
            let Ok(metadata) = fs::symlink_metadata(&per_package) else {
                continue;
            };
            if !metadata.is_file() {
                continue;
            }
            bytes += metadata.len();
            if let Some(name) = Path::new(rel).file_name() {
                removed_providers
                    .entry(name.to_string_lossy().into_owned())
                    .or_insert_with(|| pkg.clone());
            }
            if let Some(ElfNames {
                soname: Some(soname),
                ..
            }) = read_elf_names(&per_package)
            {
                removed_providers
                    .entry(soname)
                    .or_insert_with(|| pkg.clone());
            }
        }

        // What is left in target/: every file name, and the ELF objects' names.
        let mut entries = Vec::new();
        collect_entries(&target, &mut entries)?;
        entries.sort();
        let mut kept_names: BTreeSet<String> = BTreeSet::new();
        let mut objects: Vec<(String, ElfNames)> = Vec::new();
        for path in &entries {
            if let Some(name) = path.file_name() {
                kept_names.insert(name.to_string_lossy().into_owned());
            }
            if let Some(names) = read_elf_names(path) {
                if let Some(soname) = &names.soname {
                    kept_names.insert(soname.clone());
                }
                let rel = path.strip_prefix(&target).unwrap_or(path);
                objects.push((rel.display().to_string(), names));
            }
        }
        for (rel, names) in &objects {
            for needed in &names.needed {
                if let Some(pkg) = removed_providers.get(needed)
                    && !kept_names.contains(needed)
                {
                    return Err(exclude_error(format!(
                        "'{rel}' needs '{needed}', which only the excluded package '{pkg}' provides; keep '{pkg}' or leave out the object that needs it too"
                    )));
                }
            }
        }

        Ok(RootfsExcludeSummary {
            names: self.names.clone(),
            files: removed.len(),
            bytes,
            shared,
            shadowed: shadowed.into_iter().map(|(_, rel)| rel).collect(),
            shadowed_bytes,
            no_dbus,
        })
    }

    /// The D-Bus daemon's removal: each removed path is gone, and no unit left
    /// needs the daemon. Returns the files and bytes removed.
    fn verify_no_dbus(
        &self,
        target: &Path,
        removed: &[(String, String)],
    ) -> Result<(usize, u64), ImageProviderError> {
        let mut bytes = 0u64;
        for (pkg, rel) in removed {
            if fs::symlink_metadata(target.join(rel)).is_ok() {
                return Err(no_dbus_error(format!(
                    "'{rel}' is in target/ again after the removal: a later rootfs overlay or post-build script put it back"
                )));
            }
            bytes += fs::symlink_metadata(
                self.output_dir
                    .join("per-package")
                    .join(pkg)
                    .join("target")
                    .join(rel),
            )
            .ok()
            .filter(|metadata| metadata.is_file())
            .map(|metadata| metadata.len())
            .unwrap_or_default();
        }
        if let Some((unit, reason)) = unit_needing_bus(target) {
            return Err(no_dbus_error(format!(
                "'{unit}' {reason}: it needs the D-Bus daemon; leave its package out (exclude_packages) or keep the daemon"
            )));
        }
        Ok((removed.len(), bytes))
    }
}

/// The names of the ELF object at `path`, when it is a regular file that is one.
fn read_elf_names(path: &Path) -> Option<ElfNames> {
    use std::io::Read;
    let metadata = fs::symlink_metadata(path).ok()?;
    if !metadata.is_file() {
        return None;
    }
    let mut magic = [0u8; 4];
    fs::File::open(path)
        .and_then(|mut file| file.read_exact(&mut magic))
        .ok()?;
    if !has_elf_magic(&magic) {
        return None;
    }
    elf_names(&fs::read(path).ok()?)
}

/// The non-directory entries under `dir`, without following symbolic links.
fn collect_entries(dir: &Path, entries: &mut Vec<PathBuf>) -> Result<(), ImageProviderError> {
    let listing = fs::read_dir(dir)
        .map_err(|error| io_failure("failed to read the target directory", dir, error))?;
    for entry in listing.flatten() {
        let path = entry.path();
        if entry.file_type().is_ok_and(|kind| kind.is_dir()) {
            collect_entries(&path, entries)?;
        } else {
            entries.push(path);
        }
    }
    Ok(())
}

/// The digest of the exclusion a make with `exclude` applies: empty for none.
pub(crate) fn applied_digest_for(exclude: Option<&StagedRootfsExclude>) -> String {
    exclude
        .map(|exclude| exclude.digest.clone())
        .unwrap_or_default()
}

fn exclude_error(message: String) -> ImageProviderError {
    ImageProviderError::backend_command(format!("image.rootfs.exclude_packages: {message}"))
}

fn io_failure(what: &str, path: &Path, error: std::io::Error) -> ImageProviderError {
    ImageProviderError::new(
        ImageProviderErrorKind::RuntimeState,
        format!("{what} '{}': {error}", path.display()),
    )
}

